#!/usr/bin/env node
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const fontkit = require("fontkit");
const { getFontCoverageRanges } = require("../../app/shared/font-coverage");

const ROOT = path.resolve(__dirname, "..", "..");
const RENDERER_DIR = path.join(ROOT, "app", "renderer");
const FONT_DIR = path.join(RENDERER_DIR, "assets", "fonts");
const FONT_MANIFEST_FILE = path.join(FONT_DIR, "local-fonts.manifest.js");
const OUTPUT_FILE = path.join(FONT_DIR, "local-font-coverage.manifest.js");

function normalizeStyle(value) {
  const style = String(value || "").toLowerCase().trim();
  return style === "italic" || style === "oblique" ? style : "normal";
}

function getManifestFontId(entry, index) {
  if (entry && entry.id != null && String(entry.id).trim()) {
    return String(entry.id).trim();
  }
  const family = String((entry && entry.family) || "").trim();
  const weight = entry && entry.weight != null && entry.weight !== ""
    ? String(entry.weight)
    : "400";
  return `manifest-${family}-${weight}-${normalizeStyle(entry && entry.style)}-${index}`
    .replace(/\s+/g, "-")
    .toLowerCase();
}

function getSourcePath(source) {
  if (typeof source === "string") return source.trim();
  if (!source || typeof source !== "object") return "";
  return String(source.path || source.href || source.url || source.file || "").trim();
}

function getPrimarySourcePath(entry) {
  if (!entry || typeof entry !== "object") return "";
  if (Array.isArray(entry.sources)) {
    for (const source of entry.sources) {
      const value = getSourcePath(source);
      if (value) return value;
    }
  } else {
    const value = getSourcePath(entry.sources);
    if (value) return value;
  }
  return getSourcePath(entry.path || entry.file || entry.href || entry.url);
}

function loadFontManifest() {
  const code = fs.readFileSync(FONT_MANIFEST_FILE, "utf8");
  const sandbox = { window: {}, console };
  vm.runInNewContext(code, sandbox, { filename: FONT_MANIFEST_FILE });
  const entries = sandbox.window.localFontManifest;
  if (!Array.isArray(entries)) {
    throw new Error("local font manifest did not define an array");
  }
  return entries;
}

function resolveFontFile(sourcePath) {
  const resolved = path.resolve(RENDERER_DIR, sourcePath);
  if (resolved !== FONT_DIR && !resolved.startsWith(FONT_DIR + path.sep)) {
    throw new Error(`font source escapes assets/fonts: ${sourcePath}`);
  }
  return resolved;
}

function chooseFontFace(opened, entry) {
  const faces = opened && opened.fonts ? opened.fonts : opened ? [opened] : [];
  if (!faces.length) return null;
  const expectedFamily = String(entry.baseFamily || entry.family || "").trim().toLowerCase();
  return (
    faces.find((font) =>
      String((font && font.familyName) || "").trim().toLowerCase() === expectedFamily,
    ) || faces[0]
  );
}

function buildCoverageData(entries = loadFontManifest()) {
  const byFontId = {};
  entries.forEach((entry, index) => {
    const id = getManifestFontId(entry, index);
    const sourcePath = getPrimarySourcePath(entry);
    if (!id || !sourcePath) {
      throw new Error(`font manifest entry ${index} is missing an id or source`);
    }
    const fontFile = resolveFontFile(sourcePath);
    const font = chooseFontFace(fontkit.openSync(fontFile), entry);
    const coverageRanges = getFontCoverageRanges(font);
    if (!coverageRanges) {
      throw new Error(`font manifest entry ${id} has no readable character coverage`);
    }
    byFontId[id] = coverageRanges;
  });
  return { version: 1, byFontId };
}

function renderCoverageManifest(data) {
  const lines = [
    "// Auto-generated by tools/fonts/generate-font-coverage.js. Do not edit by hand.",
    "window.localFontCoverageManifest = {",
    "  version: 1,",
    "  byFontId: {",
  ];
  Object.entries(data.byFontId).forEach(([id, ranges]) => {
    lines.push(`    ${JSON.stringify(id)}: ${JSON.stringify(ranges)},`);
  });
  lines.push("  },", "};", "");
  return lines.join("\n");
}

function buildCoverageManifestText() {
  return renderCoverageManifest(buildCoverageData());
}

function main() {
  const data = buildCoverageData();
  const output = renderCoverageManifest(data);
  fs.writeFileSync(OUTPUT_FILE, output, "utf8");
  const count = Object.keys(data.byFontId).length;
  console.log(`Updated font coverage manifest with ${count} entries.`);
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(`Failed to generate font coverage: ${error.message}`);
    process.exitCode = 1;
  }
}

module.exports = {
  FONT_MANIFEST_FILE,
  OUTPUT_FILE,
  buildCoverageData,
  buildCoverageManifestText,
  getManifestFontId,
  getPrimarySourcePath,
  loadFontManifest,
  renderCoverageManifest,
};
